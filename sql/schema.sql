-- Não execute no ERP. Nenhuma tabela existente é excluída.
-- Nenhum registro ou tabela preexistente e removido.
CREATE TABLE IF NOT EXISTS public.saj_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer text NOT NULL CHECK (length(trim(customer)) BETWEEN 1 AND 160),
  phone text NOT NULL DEFAULT '',
  plate text NOT NULL DEFAULT '',
  seller text NOT NULL CHECK (seller IN ('Antonio','Jean')),
  mechanic text NOT NULL DEFAULT '' CHECK (mechanic IN ('','Sérgio','Marcelo','Zé')),
  notes text NOT NULL DEFAULT '',
  items jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(items) = 'array'),
  payments jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(payments) = 'array'),
  total_cents bigint NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','completed')),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
CREATE INDEX IF NOT EXISTS saj_orders_created_at_idx ON public.saj_orders (created_at DESC);
CREATE INDEX IF NOT EXISTS saj_orders_status_idx ON public.saj_orders (status);

CREATE TABLE IF NOT EXISTS public.saj_destinations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 120),
  type text NOT NULL CHECK (type IN ('pos','pix','bank','other')),
  cnpj text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
